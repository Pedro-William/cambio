export const LOCALES = { pt: 'pt-BR', en: 'en-US' }

export function translate(lang, key, vars = {}) {
  const text = translations[lang]?.[key] ?? translations.pt[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`))
}